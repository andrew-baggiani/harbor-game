/**
 * Role-based tracks. These close the role-based training controls that a general shift cannot:
 * NIST 800-53 AT-3, NIST 800-171 3.2.2, CMMC AT.L2-3.2.2, CIS 14.9 and NIST CSF PR.AT-02.
 * Each is a short shift for people with a specific security duty, assigned in the portal.
 */
const ROLE: Controls = {
  "NIST_800-53r5": ["AT-3"],
  "NIST_800-171r2": ["3.2.2"],
  CMMC_L2: ["AT.L2-3.2.2"],
  "CIS_v8.1": ["14.9"],
  "CSF_2.0": ["PR.AT-02"],
};
const plus = (extra: Controls): Controls => {
  const out: Controls = {};
  for (const key of new Set([...Object.keys(ROLE), ...Object.keys(extra)])) out[key] = [...(ROLE[key] ?? []), ...(extra[key] ?? [])];
  return out;
};

